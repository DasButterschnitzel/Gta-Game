export function trafficPool(district: number, night: boolean): { ids: string[]; weights: number[] } {
  const ids: string[] = [];
  const weights: number[] = [];
  for (const d of Object.values(VEHICLES)) {
    if (d.traffic <= 0 || d.emergency) continue;
    let w = d.traffic;
    // richer cars in the north, old cars in Betonhausen, trucks in the harbour
    if (district === 8 /*Villen*/ || district === 7 /*Turm*/) {
      if (d.id === 'elfer' || d.id === 'quadro' || d.id === 'b5' || d.id === 'mercator') w *= 3;
      if (d.id === 'rennpappe') w *= 0.2;
    }
    if (district === 3 /*Platte*/ && (d.id === 'rennpappe' || d.id === 'mantis')) w *= 2.5;
    if ((district === 4 || district === 5) /*Hafen/Industrie*/ && (d.heavy || d.id === 'sprinto')) w *= 4;
    if (night && d.id === 'bus') w *= 0.3;
    ids.push(d.id);
    weights.push(w);
  }
  return { ids, weights };
}
