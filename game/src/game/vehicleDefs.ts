// Vehicle catalogue. Parody brands inspired by German automotive design language (no real brands).

export type Drive = 'FWD' | 'RWD' | 'AWD';
export type EngineSound = 'i4' | 'i6' | 'v8' | 'boxer' | 'diesel' | 'two' | 'ev' | 'truck';
export type BodyStyle = 'hatch' | 'sedan' | 'wagon' | 'coupe' | 'van' | 'truck' | 'bus' | 'micro' | 'firetruck' | 'garbage';

export interface ModelSpec {
  body: BodyStyle;
  /** cabin base extents along length (0 = rear bumper, 1 = front bumper) */
  cabRear: number;
  cabFront: number;
  /** roof extents along length */
  roofRear: number;
  roofFront: number;
  beltZ: number; // height of the lower body top (m)
  roofZ: number; // roof height (m)
  roofInset: number; // how much narrower the roof is on each side (m)
  chamfer: number; // footprint corner chamfer (m)
  hoodDrop: number; // front edge lowered by (m)
  lightbar?: 'police' | 'ambulance' | 'fire' | 'yellow' | 'magnet';
  taxiSign?: boolean;
  ladder?: boolean;
  spoiler?: boolean;
  /** cargo box for trucks/vans: extents along length + height */
  box?: { from: number; to: number; z: number; color?: number };
  glass?: number;
  trim?: number;
  wheelR?: number;
  /** emergency vehicles: livery drawing key */
  livery?: 'police' | 'taxi' | 'ambulance' | 'fire' | 'parcel' | 'sek' | 'gti' | 'bus' | 'garbage' | 'race' | 'bse';
}

export interface VehicleDef {
  id: string;
  name: string;
  length: number;
  width: number;
  height: number;
  wheelbase: number;
  mass: number; // kg
  power: number; // W
  topSpeed: number; // m/s
  accelCap: number; // m/s^2 traction-limited launch
  grip: number; // tyre friction coefficient
  drive: Drive;
  brake: number; // m/s^2
  steerMax: number; // rad
  engine: EngineSound;
  health: number;
  colors: number[];
  model: ModelSpec;
  siren?: boolean;
  /** relative spawn weight in traffic per district class */
  traffic: number;
  emergency?: 'police' | 'ambulance' | 'fire' | 'sek';
  heavy?: boolean;
  /** extra armour: incoming damage is multiplied by this */
  armor?: number;
  /** price on the export list / value */
  value: number;
}

