// Scripted gameplay test: enter car, drive, screenshots + stats.
import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
import path from 'node:path';
import fs from 'node:fs';
const outDir = process.argv[2] || 'test-output';
fs.mkdirSync(outDir, { recursive: true });
const url = process.env.GAME_URL || 'http://localhost:8765/?autostart';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 600 }, deviceScaleFactor: 1 });
const logs = [];
page.on('console', (m) => logs.push(`[${m.type()}] ${m.text()}`));
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}\n${e.stack}`));
await page.goto(url, { waitUntil: 'commit' });
await page.waitForFunction(() => window.__game && window.__game.player, null, { timeout: 120000 });
await page.waitForTimeout(800);
const shot = async (name) => { await page.screenshot({ path: path.join(outDir, name + '.png') }); };
const stats = async (label) => { const s = await page.evaluate(() => window.__game.stats()); console.log(label, JSON.stringify(s)); return s; };
const sim = async (secs, inp) => page.evaluate(([s, i]) => window.__game.simulate(s, i), [secs, inp]);
await stats('start');
await shot('01_start');
await sim(1.8, { enterPressed: true });
await stats('after-enter');
await shot('02_in_car');
await sim(2.5, { throttle: 1 });
await stats('accelerating');
await shot('03_driving');
await sim(1.2, { throttle: 1, steer: 1 });
await stats('steer-right');
await sim(0.8, { throttle: 0.5, steer: -1, handbrake: true });
await stats('handbrake');
await shot('04_handbrake');
await sim(4, { throttle: 0.7 });
await stats('cruise');
await shot('05_cruise');
await page.evaluate(() => window.__game.setClock(23));
await sim(0.5, { throttle: 0.5 });
await shot('06_night');
console.log(logs.filter(l => !l.includes('generated') && !l.includes('ready')).slice(-25).join('\n'));
await browser.close();
