// Mobile emulation: radio button, pause menu, settings, map.
import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
import path from 'node:path';
import fs from 'node:fs';
const outDir = process.argv[2] || 'test-output';
fs.mkdirSync(outDir, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const ctx = await browser.newContext({ viewport: { width: 915, height: 412 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message + '\n' + e.stack));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://localhost:8765/?free', { waitUntil: 'commit' });
await page.waitForSelector('.startbtn', { timeout: 120000 });
await page.tap('.startbtn');
await page.waitForTimeout(1200);
const tapEl = async (sel) => {
  const b = await page.evaluate((sel) => { const el = [...document.querySelectorAll(sel)].find((e) => e.offsetParent !== null); if (!el) return null; const r = el.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; }, sel);
  if (!b) throw new Error('not found ' + sel);
  await page.touchscreen.tap(b.x, b.y);
};
// enter Gisela
const btn = await page.evaluate(() => { const els = [...document.querySelectorAll('.tbtn')].filter(e => e.style.display !== 'none' && e.textContent.includes('EINSTEIGEN')); const r = els[0].getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; });
await page.touchscreen.tap(btn.x, btn.y);
await page.waitForTimeout(2600);
await tapEl('.hud .radio');
await page.waitForTimeout(700);
const radio = await page.evaluate(() => ({ station: window.__game.radio.current, inVeh: window.__game.player.inVehicle, banner: document.querySelector('.rbanner').textContent }));
console.log('radio', JSON.stringify(radio));
await page.screenshot({ path: path.join(outDir, 'n1_radio.png') });
await tapEl('.hud .pause');
await page.waitForTimeout(400);
await page.screenshot({ path: path.join(outDir, 'n2_menu.png') });
await tapEl('.pm-btn[data-a=settings]');
await page.waitForTimeout(300);
await page.screenshot({ path: path.join(outDir, 'n3_settings.png') });
await tapEl('.pm-seg[data-k=steer] button[data-v=buttons]');
await tapEl('.pm-btn[data-a=main]');
await tapEl('.pm-btn[data-a=help]');
await page.waitForTimeout(300);
await page.screenshot({ path: path.join(outDir, 'n4_help.png') });
await tapEl('.pm-btn[data-a=main]');
await tapEl('.pm-btn[data-a=map]');
await page.waitForTimeout(400);
await page.screenshot({ path: path.join(outDir, 'n5_map.png') });
await tapEl('.mbtn.close');
await tapEl('.pm-btn[data-a=resume]');
await page.waitForTimeout(500);
const st = await page.evaluate(() => ({ paused: window.__game.paused, steer: window.__game.settings.steer, stored: localStorage.getItem('hafengold.settings') }));
console.log('after', JSON.stringify(st));
await page.screenshot({ path: path.join(outDir, 'n6_steerbuttons.png') });
console.log('errors:', errors.length ? errors.join('\n') : 'none');
await browser.close();
